export type SmartCullingTextKey = keyof typeof zh;

export function useSmartCullingText() {
  const { i18n } = useTranslation();
  const isChinese = i18n.resolvedLanguage?.toLowerCase().startsWith('zh') ?? false;
  return useCallback((key: SmartCullingTextKey) => (isChinese ? zh : en)[key], [isChinese]);
}

export function useSmartCullingModes() {
  const { i18n } = useTranslation();
  return i18n.resolvedLanguage?.toLowerCase().startsWith('zh') ? zhModes : enModes;
}

export function useSmartCullingReasonText() {
  const { i18n } = useTranslation();
  const isChinese = i18n.resolvedLanguage?.toLowerCase().startsWith('zh') ?? false;
  return useCallback(
    (codes: string[]) =>
      codes
        .slice(0, 2)
        .map((code) => reasonText(code, isChinese))
        .join(isChinese ? '；' : '; '),
    [isChinese],
  );
}

export function useSmartCullingStoryText() {
  const { i18n } = useTranslation();
  const isChinese = i18n.resolvedLanguage?.toLowerCase().startsWith('zh') ?? false;
  return useCallback(
    (story: string) => {
      const [kind, index] = story.split(':');
      if (!index) return story;
      if (kind === 'similar') return isChinese ? `相似组 ${index}` : `Similar group ${index}`;
      if (kind === 'single') return isChinese ? `单张故事 ${index}` : `Single photo ${index}`;
      return story;
    },
    [isChinese],
  );
}
