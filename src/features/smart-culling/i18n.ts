export function keyPersonIdentityLabel(priority: number) {
  return priority >= 1 && priority <= 26 ? String.fromCharCode(64 + priority) : String(priority);
}

function reasonText(code: string, isChinese: boolean) {
  const keyPersonMatch = /^key_person_(\d+)_(confirmed|missing|suspected|ambiguous|unknown)$/.exec(code);
  if (keyPersonMatch) {
    const [, priority, state] = keyPersonMatch;
    const label = keyPersonIdentityLabel(Number(priority));
    const zhState = {
      confirmed: '已确认包含',
      missing: '未确认包含，星级限制在低星范围',
      suspected: '疑是关键人物，请人工确认',
      ambiguous: '可能匹配多人，请人工确认',
      unknown: '无法可靠判断，请人工确认',
    }[state];
    const enState = {
      confirmed: 'confirmed present',
      missing: 'not confirmed present; rating is capped in the low range',
      suspected: 'possibly present; verify manually',
      ambiguous: 'matches more than one candidate; verify manually',
      unknown: 'cannot be determined reliably; verify manually',
    }[state];
    return isChinese ? `人物 ${label}：${zhState}` : `Person ${label}: ${enState}`;
  }
  const dictionary = isChinese ? zhReasons : enReasons;
  return dictionary[code] ?? (isChinese ? '建议人工确认' : 'Manual review recommended');
}

